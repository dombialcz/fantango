import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";

const baseURL = process.argv[2] ?? "http://127.0.0.1:4173";
const browser = await chromium.launch({ headless: true });
await mkdir("output/roster-ui", { recursive: true });
const errors = [];
async function game(viewport, random = .05) {
  const context = await browser.newContext({ viewport });
  await context.addInitScript((value) => { Math.random = () => value; }, random);
  const page = await context.newPage();
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto(`${baseURL}/dungeon.html`);
  await page.waitForFunction(() => window.render_game_to_text);
  const state = async () => JSON.parse(await page.evaluate(() => window.render_game_to_text()));
  const prepare = () => page.locator('.town-panorama [data-town-action="close"]').click();
  const spin = async () => { await page.locator('[data-roster-action="roll"]').click(); await page.evaluate(() => window.advanceTime(1500)); };
  return { context, page, state, prepare, spin };
}

try {
  const { context, page, state, prepare, spin } = await game({ width: 1440, height: 1000 });
  assert.equal((await state()).view, "town");
  assert.equal((await state()).rolledToday, false);
  assert.equal((await state()).offerCount, 0);
  await page.locator('.town-inspector [data-open-upgrade="tavern"]').click();
  await page.locator('.town-upgrade-dialog [data-upgrade="tavern"]').click();
  assert.equal((await state()).tavernLevel, 2);
  assert.equal((await state()).gold, 7);
  assert.equal((await state()).offerCount, 0);
  await page.screenshot({ path: "output/roster-ui/town.png", fullPage: true });
  await prepare();
  assert.equal((await state()).offerCount, 0);
  assert.equal(await page.locator('[data-hire]').count(), 0);
  await page.screenshot({ path: "output/roster-ui/sealed.png", fullPage: true });
  // Enter on the focused roll button starts one roll, not an expedition.
  await page.locator('[data-roster-action="roll"]').focus();
  await page.keyboard.press("Enter");
  assert.equal((await state()).gold, 7);
  assert.equal((await state()).nextRollCost, 1);
  assert.ok((await state()).rollRemainingMs > 0);
  assert.equal(await page.locator('[data-hire]').count(), 0);
  assert.equal(await page.locator('[data-roster-action="start"]').isDisabled(), true);
  await page.keyboard.press("r");
  await page.keyboard.press("t");
  assert.equal((await state()).view, "tavern");
  assert.equal((await state()).gold, 7);
  await page.evaluate(() => window.advanceTime(1500));
  assert.equal((await state()).offerCount, 5);
  assert.ok((await state()).offers.every((hero) => hero.level === 2));
  await page.locator('[data-offer]').first().click();
  assert.equal((await state()).bench.length, 0);
  assert.ok((await state()).selectedOfferId);
  await page.locator('[data-hire]').first().click();
  assert.equal((await state()).gold, 7);
  assert.equal((await state()).bench.length, 1);
  await page.locator('[data-roster-action="upgrade"]').click();
  assert.equal((await state()).bench[0].level, 3);
  assert.equal((await state()).gold, 3);
  const lockedId = (await state()).bench[0].id;
  await spin();
  assert.equal((await state()).gold, 2);
  assert.equal((await state()).rerollCost, 2);
  assert.equal((await state()).bench[0].id, lockedId);
  await page.locator('.roster-header > div [data-roster-action="town"]').click();
  const offers = (await state()).offers;
  await prepare();
  assert.deepEqual((await state()).offers, offers);
  assert.equal((await state()).rerollCost, 2);
  await spin();
  assert.equal((await state()).gold, 0);
  assert.equal((await state()).rerollCost, 3);
  assert.equal(await page.locator('[data-roster-action="roll"]').isDisabled(), true);
  const unchangedOffers = (await state()).offers;
  await page.keyboard.press("r");
  assert.deepEqual((await state()).offers, unchangedOffers);
  for (let index = 0; index < 5; index += 1) await page.locator('[data-hire]').first().click();
  assert.equal((await state()).bench.length, 6);
  assert.equal((await state()).bench.filter((hero) => hero.active).length, 4);
  await page.locator('[data-hero]').first().click();
  await page.locator('[data-roster-action="toggle"]').click();
  assert.equal((await state()).bench.filter((hero) => hero.active).length, 3);
  await page.locator(`[data-hero="${lockedId}"]`).click();
  await page.locator('[data-roster-action="toggle"]').click();
  assert.equal((await state()).bench.filter((hero) => hero.active).length, 4);
  await page.screenshot({ path: "output/roster-ui/company.png", fullPage: true });
  await page.locator('[data-roster-action="start"]').click();
  if (await page.locator('.roster-departure-dialog').evaluate(dialog => dialog.open)) await page.locator('[data-departure="confirm"]').click();
  assert.equal((await state()).view, "battle");
  await page.locator('[data-battle-action="pause"]').click();
  await page.locator('[data-battle-action="flee"]').click();
  await page.locator('[data-battle-action="flee-confirm"]').click();
  await page.locator('[data-battle-action="next-day"]').click();
  assert.equal((await state()).view, "town");
  assert.equal((await state()).day, 2);
  assert.equal((await state()).offerCount, 0);
  assert.equal((await state()).rolledToday, false);
  assert.equal((await state()).nextRollCost, 0);
  assert.equal((await state()).bench.length, 6);
  await prepare();
  await spin();
  assert.equal((await state()).offerCount, 6);
  assert.equal((await state()).gold, 0);
  assert.equal(await page.locator('[data-hire]').first().isDisabled(), true);
  const dismissedId = (await state()).bench[0].id;
  await page.locator(`[data-hero="${dismissedId}"]`).click();
  await page.locator('[data-roster-action="dismiss"]').click();
  assert.equal((await state()).bench.length, 5);
  assert.equal(await page.locator('[data-hire]').first().isEnabled(), true);
  await page.locator('[data-hire]').first().click();
  assert.equal((await state()).bench.length, 6);
  await page.locator('.roster-header > div [data-roster-action="town"]').click();
  await page.locator('[data-town-action="reset"]').click();
  assert.equal((await state()).view, "town");
  assert.equal((await state()).day, 1);
  assert.equal((await state()).gold, 10);
  assert.equal((await state()).rolledToday, false);
  assert.equal((await state()).bench.length, 0);
  assert.equal((await state()).tavernLevel, 1);
  await context.close();
  console.log("Daily flow, free/paid rolls, Tavern odds, locked bench, management, battle and reset: passed");

  for (const [name, width, height] of [["phone", 390, 844], ["small-phone", 320, 740], ["landscape", 844, 390], ["tablet", 900, 1000]]) {
    const current = await game({ width, height }, .8);
    if (name === "small-phone") await current.page.emulateMedia({ reducedMotion: "reduce" });
    await current.page.screenshot({ path: `output/roster-ui/town-${name}.png`, fullPage: true });
    if (width <= 760) {
      await current.page.locator('[data-district="tavern"]').click();
      await current.page.locator('.town-sheet [data-open-upgrade="tavern"]').click();
      await current.page.locator('.town-upgrade-dialog [data-upgrade="tavern"]').click();
      assert.equal((await current.state()).tavernLevel, 2);
      await current.page.locator('[data-town-action="dismiss"]').click();
    }
    await current.prepare();
    await current.page.screenshot({ path: `output/roster-ui/sealed-${name}.png`, fullPage: true });
    await current.spin();
    assert.equal((await current.state()).offers.length, 5);
    await current.page.locator('[data-offer]').last().click();
    assert.equal((await current.state()).bench.length, 0);
    await current.page.locator('[data-hire]').last().click();
    assert.equal((await current.state()).bench.length, 1);
    await current.page.locator('[data-roster-action="upgrade"]').click();
    await current.page.locator('[data-roster-action="toggle"]').click();
    assert.equal((await current.state()).bench[0].active, false);
    await current.page.locator('[data-roster-action="toggle"]').click();
    await current.page.screenshot({ path: `output/roster-ui/reel-${name}.png`, fullPage: true });
    assert.equal(await current.page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const images = await current.page.locator('.roster-screen img').evaluateAll((images) => images.every((image) => image.complete && image.naturalWidth));
    assert.ok(images);
    await current.context.close();
    console.log(`${name}: passed`);
  }
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
